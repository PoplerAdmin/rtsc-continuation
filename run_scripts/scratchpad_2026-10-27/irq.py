import numpy as np, spglib
a=4.05; fcc=[[0,a/2,a/2],[a/2,0,a/2],[a/2,a/2,0]]
def bcc(a): return [[-a/2,a/2,a/2],[a/2,-a/2,a/2],[a/2,a/2,-a/2]]
hexc=[[3.086,0,0],[-1.543,2.672555,0],[0,0,3.524]]
cells={
 'Al':((fcc,[[0,0,0]],[1]),),
 'Pb':((np.array(fcc)*4.95/4.05,[[0,0,0]],[1]),),
 'Nb':((bcc(3.30),[[0,0,0]],[1]),),
 'MgB2':((hexc,[[0,0,0],[1/3,2/3,.5],[2/3,1/3,.5]],[1,2,2]),),
 'H3S':((bcc(2.98),np.linalg.solve(np.array(bcc(2.98)).T,np.array([[0,0,0],[1.49,0,0],[0,1.49,0],[0,0,1.49]]).T).T,[1,2,2,2]),),
}
grids={'Al':[(8,8,8),(16,16,16),(32,32,32)],'Pb':[(8,8,8),(16,16,16),(32,32,32)],'Nb':[(8,8,8),(16,16,16),(32,32,32)],
 'MgB2':[(6,6,4),(6,6,6),(18,18,12),(24,24,18),(36,36,24)],'H3S':[(6,6,6),(8,8,8),(18,18,18),(24,24,24),(36,36,36)]}
for n,(c,) in cells.items():
    print(n, spglib.get_spacegroup(c,symprec=1e-3), end=': ')
    for g in grids[n]:
        m,_=spglib.get_ir_reciprocal_mesh(g,c,is_shift=[0,0,0])
        print(f"{g}->{len(np.unique(m))}", end='  ')
    print()
