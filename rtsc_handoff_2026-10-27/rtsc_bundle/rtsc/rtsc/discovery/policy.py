"""Deterministic bandit search policy (DISCOVERY.md section 5).  HEURISTIC: it only decides
what is generated and in which order candidates go to DFT.  It never writes a status other than
DEFERRED (enforced by the ledger).

Arms are goal x chemical system x pressure x space group (optional) x generator.  Each arm has a
Beta(1 + S, 1 + F) posterior, where every DFT outcome of a material generated by the arm adds
reward r in [0, 1] to S and 1 - r to F (``reward``); ML-unstable deferrals and requests that
produced no new structure add failures.  ``thompson`` samples the posteriors, ``ucb`` uses
mean + c * sqrt(2 ln N / n).  An exploration floor reserves ceil(floor * n) requests per round for
arms never pulled.  The RNG is seeded with (seed, round index) and the statistics are recomputed
from the ledger, so a continued run reproduces the same choices.
"""
from __future__ import annotations

import math
import random
from dataclasses import dataclass, field
from typing import Any, Iterable

from ..constants import A0
from ..status import Status


@dataclass(frozen=True)
class Arm:
    goal_id: str
    chemsys: tuple[str, ...]
    pressure_GPa: float
    space_group: int | None
    generator: str

    @property
    def key(self) -> str:
        sg = "any" if self.space_group is None else str(self.space_group)
        return f"{self.goal_id}|{'-'.join(self.chemsys)}|P{self.pressure_GPa:g}|sg{sg}|{self.generator}"

    def to_dict(self) -> dict[str, Any]:
        return {"goal_id": self.goal_id, "chemsys": list(self.chemsys),
                "pressure_GPa": self.pressure_GPa, "space_group": self.space_group,
                "generator": self.generator, "key": self.key}


def build_arms(goals: Iterable, generator_names: Iterable[str]) -> list[Arm]:
    arms = {}
    for g in goals:
        if not g.enabled:
            continue
        for cs in g.chemical_systems:
            for p in g.pressures_GPa:
                for sg in g.space_groups:
                    for gen in generator_names:
                        a = Arm(g.id, tuple(cs), float(p), sg, gen)
                        arms[a.key] = a
    return [arms[k] for k in sorted(arms)]


def reward(status: Status | str, T_low_K: float | None, T_up_K: float | None, T_star_K: float,
           A_hi_K: float | None = None, kappa_hi_K: float | None = None) -> float:
    """Heuristic reward in [0, 1] of one DFT-level outcome for the arm's goal."""
    st = Status(status)
    if st is Status.CERTIFIED_CANDIDATE:
        return 1.0
    ceiling = None
    for x in (T_up_K, None if A_hi_K is None else A_hi_K / A0, None if kappa_hi_K is None else kappa_hi_K / A0):
        if x is not None and math.isfinite(float(x)):
            ceiling = float(x) if ceiling is None else min(ceiling, float(x))
    if st is Status.UNDECIDED:
        lo = 0.0 if T_low_K is None else min(1.0, max(0.0, float(T_low_K) / T_star_K))
        return 0.6 + 0.3 * lo
    if st is Status.REJECTED_PROVEN:
        return 0.1 if ceiling is None else 0.5 * min(1.0, max(0.0, ceiling / T_star_K))
    if st is Status.EXCLUDED_ASSUMPTION:
        return 0.05
    return 0.0


@dataclass
class ArmStats:
    pulls: int = 0
    S: float = 0.0
    F: float = 0.0
    outcomes: int = 0

    @property
    def mean(self) -> float:
        return (1.0 + self.S) / (2.0 + self.S + self.F)

    def to_dict(self) -> dict[str, Any]:
        return {"pulls": self.pulls, "S": round(self.S, 6), "F": round(self.F, 6),
                "outcomes": self.outcomes, "mean": round(self.mean, 6)}


@dataclass
class BanditPolicy:
    arms: list[Arm]
    seed: int = 0
    kind: str = "thompson"
    exploration_floor: float = 0.25
    ucb_c: float = 1.0
    last_scores: dict[str, float] = field(default_factory=dict)

    def rng(self, round_idx: int, salt: str = "") -> random.Random:
        return random.Random(f"rtsc-discovery:{self.seed}:{round_idx}:{salt}")

    def propose(self, round_idx: int, n: int, stats: dict[str, ArmStats]) -> list[Arm]:
        if not self.arms or n <= 0:
            return []
        rng = self.rng(round_idx)
        st = {a.key: stats.get(a.key, ArmStats()) for a in self.arms}
        chosen: list[Arm] = []
        unexplored = [a for a in self.arms if st[a.key].pulls == 0]
        if unexplored and self.exploration_floor > 0:
            k = min(len(unexplored), max(1, math.ceil(self.exploration_floor * n)), n)
            pool = list(unexplored)
            rng.shuffle(pool)
            chosen.extend(pool[:k])
        total = sum(s.pulls for s in st.values()) + 1
        scores: dict[str, float] = {}
        for a in self.arms:
            s = st[a.key]
            if self.kind == "ucb":
                bonus = float("inf") if s.pulls == 0 else self.ucb_c * math.sqrt(2 * math.log(total) / s.pulls)
                scores[a.key] = s.mean + bonus
            else:
                scores[a.key] = rng.betavariate(1.0 + s.S, 1.0 + s.F)
        tie = {a.key: rng.random() for a in self.arms}
        ranked = sorted(self.arms, key=lambda a: (-scores[a.key], -tie[a.key], a.key))
        self.last_scores = scores
        taken = {a.key for a in chosen}
        rest = [a for a in ranked if a.key not in taken] or ranked
        i = 0
        while len(chosen) < n:
            chosen.append(rest[i % len(rest)])
            i += 1
        return chosen
